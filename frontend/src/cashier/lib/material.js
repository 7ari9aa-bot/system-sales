// الخامة (نوع القماش) نص واحد على المنتج، زي الموسم بالظبط: مسافة زيادة تتشال، والفاضي معناه
// "مفيش خامة" مش خامة اسمها "". والحالتين اللي بيغلطوا فيهم كل حقل نصي بيتبعت للخادم:
//
//  1. القيمة الغايبة (null / undefined) لَو اتكتبت في الـURL أو في الـJSON بتبقى النص "null"،
//     والفلتر بيبقى بيدوّر على خامة اسمها "null" حرفيًا. هنا بترجع فاضية.
//  2. صاحب المحل ممكن يكتب "null" بنفسه بالغلط في خانة الخامة. النص ده مش خامة، فبيتعامل كفاضي
//     كمان، عشان "null" ما يوصلش للسيرفر لا كخامة ولا كفلتر.
//
// الدالة نقية: نفس المدخل دايمًا نفس المخرج، ومفيش أي شبكة ولا React.

/** أقصى طول يقبله الخادم للخامة (Product.material = String(60)). */
export const MATERIAL_MAX_LENGTH = 60;

/** النصوص اللي معناها "مفيش قيمة" لو وصلت كنص، مش كخامة حقيقية. */
const BLANK_WORDS = new Set(["null", "undefined"]);

/**
 * الخامة كنص جاهز للإرسال أو للعرض: مسافات الأطراف مشالة، والقيمة الغايبة أو الفاضية أو النص
 * "null"/"undefined" بترجع "" — يعني "مفيش خامة". أي نص تاني بيرجع زي ما هو بعد التشذيب.
 */
export function materialText(value) {
  if (value === null || value === undefined) return "";
  const text = String(value).trim();
  if (!text || BLANK_WORDS.has(text.toLowerCase())) return "";
  return text;
}
